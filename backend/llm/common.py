def secret(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise RuntimeError(f"Не задан секрет {name} — задайте переменную окружения (см. .env.example)")
    return value


def user_message(columns, rows) -> str:
    lines = [" | ".join(str(c) for c in columns)]
    for r in rows:
        lines.append(" | ".join("" if v is None else str(v) for v in r))
    return "Вот первые строки таблицы (разделитель — |):\n" + "\n".join(lines)
